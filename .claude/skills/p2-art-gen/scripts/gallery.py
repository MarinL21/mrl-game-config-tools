def _init_html(gallery_path: Path):
    nav_links = " ".join(f'<a href="#{m}">{title}</a>' for m, title in MODULE_TITLES.items())
    sections = []
    for m, title in MODULE_TITLES.items():
        sections.append(
            f'<section id="{m}">\n  <h2>{title}</h2>\n  {MARKER[m]}\n  '
            f'<div class="empty empty-{m}">暂无生成，运行 skill 后自动填充</div>\n</section>'
        )
    out = _TEMPLATE.replace("__NAV__", nav_links).replace("__SECTIONS__", "\n".join(sections))
    gallery_path.parent.mkdir(parents=True, exist_ok=True)
    gallery_path.write_text(out, encoding="utf-8")


