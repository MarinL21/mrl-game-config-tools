# 产品名展示（grfal API 键 → 用户看到的名字）
ENGINE_DISPLAY = {
    "gemini": "nano-banana",    # 谷歌 Nano Banana 2
}


def append_batch(
    gallery_path: Path,
    module: str,
    timestamp: str,
    prompt: str,
    engines: list[str],
    ref_paths: list[str],
    items: list[dict],     # [{"path": "images/chest/xxx.png", "engine": "gpt"}, ...]
    duration_s: float,
    # legacy aliases for backward compat
    engine: str | None = None,
    image_paths: list[str] | None = None,
):
    """把一个新批次插入到 gallery.html 对应模块区的最顶部。"""
    # legacy 兼容：旧调用方传 engine + image_paths
    if not items and image_paths is not None:
        eng = engine or (engines[0] if engines else "gpt")
        items = [{"path": p, "engine": eng} for p in image_paths]
    if not engines and engine:
        engines = [engine]

    if not gallery_path.exists():
        _init_html(gallery_path)
    doc = gallery_path.read_text(encoding="utf-8")

    # 渲染 refs：外部路径的 ref 图拷贝到 gallery 本地 refs/ 目录，避免 Chrome file:// 跨目录限制
    ref_html = []
    gallery_dir = gallery_path.parent
    refs_dir = gallery_dir / "refs" / module
    refs_dir.mkdir(parents=True, exist_ok=True)
    for i, rp in enumerate(ref_paths):
        rp_abs = Path(rp).resolve()
        # 如果已经在 gallery_dir 下，直接用相对路径；否则拷贝到 refs/ 后再引用
        try:
            rel = rp_abs.relative_to(gallery_dir)
            ref_src = str(rel)
        except ValueError:
            local = refs_dir / rp_abs.name
            if not local.exists() or local.stat().st_size != rp_abs.stat().st_size:
                shutil.copy2(rp_abs, local)
            ref_src = str(local.relative_to(gallery_dir))
        label = "竞品" if (module == "ui" and i == 0) else "P2 锚点"
        ref_src_escaped = html.escape(ref_src, quote=True)
        ref_html.append(
            f'<div class="ref">'
            f'<img src="{ref_src_escaped}" alt="{label}">'
            f'<span class="ref-label">{label}：{html.escape(rp_abs.name)}</span>'
            f'</div>'
        )
    refs_block = f'<div class="refs">{"".join(ref_html)}</div>' if ref_html else ""

    # 渲染 grid（生成 512px JPG 缩略图，避开 Chrome 同屏渲染 4K PNG 崩掉变黑）
    cells = []
    for i, it in enumerate(items):
        rel_path = it["path"]
        eng = it.get("engine", "?")
        rel_escaped = html.escape(rel_path, quote=True)
        abs_path = (gallery_path.parent / rel_path).resolve()
        abs_escaped = html.escape(str(abs_path), quote=True)
        # thumb: thumbs/ 镜像目录 + .jpg 后缀
        thumb_rel = Path("thumbs") / Path(rel_path).with_suffix(".jpg")
        thumb_abs = gallery_path.parent / thumb_rel
        thumb_src = str(thumb_rel) if _make_thumb(abs_path, thumb_abs) else rel_path
        thumb_escaped = html.escape(thumb_src, quote=True)
        color = ENGINE_COLOR.get(eng, "#666")
        eng_display = ENGINE_DISPLAY.get(eng, eng)
        cells.append(
            f'<div class="cell">'
            f'<img src="{thumb_escaped}" alt="{i}" loading="lazy">'
            f'<div class="badge" style="background:{color};">{html.escape(eng_display)}</div>'
            f'<div class="actions">'
            f'<button onclick="copyImg(this, \'{rel_escaped}\')">复制图片</button>'
            f'<button onclick="copyPath(this, \'{abs_escaped}\')">复制路径</button>'
            f'</div>'
            f'</div>'
        )
    grid_block = f'<div class="grid">{"".join(cells)}</div>'

    engines_label = " + ".join(
        f"{ENGINE_DISPLAY.get(e, e)} × {sum(1 for it in items if it['engine']==e)}"
        for e in engines
    )

    batch_html = (
        f'<div class="batch">'
        f'<div class="batch-meta">'
        f'<span><b>{time.strftime("%Y-%m-%d %H:%M", time.strptime(timestamp, "%Y%m%d_%H%M%S"))}</b></span>'
        f'<span>引擎: <b>{html.escape(engines_label)}</b></span>'
        f'<span>张数: <b>{len(items)}</b></span>'
        f'<span>耗时: <b>{duration_s:.0f}s</b></span>'
        f'</div>'
        f'<div class="batch-prompt">{html.escape(prompt)}</div>'
        f'{refs_block}'
        f'{grid_block}'
        f'</div>'
    )

    # 插到 marker 前 + 清掉 empty 占位
    marker = MARKER[module]
    if marker not in doc:
        # 老版本文件没有 marker，重建
        _init_html(gallery_path)
        doc = gallery_path.read_text(encoding="utf-8")

    # 移除该模块的 empty 占位（如果有）
    doc = doc.replace(f'<div class="empty empty-{module}">暂无生成，运行 skill 后自动填充</div>\n', "")
    # 在 marker 后插入（让最新批次出现在模块顶部）
    doc = doc.replace(marker, f"{marker}\n{batch_html}", 1)
    gallery_path.write_text(doc, encoding="utf-8")
