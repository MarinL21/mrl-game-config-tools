THUMB_MAX_PX = 512


def _make_thumb(src: Path, thumb: Path) -> bool:
    """用 macOS sips 生成 512px JPG 缩略图。已存在且不旧则跳过。成功返回 True。"""
    if thumb.exists() and thumb.stat().st_mtime >= src.stat().st_mtime:
        return True
    thumb.parent.mkdir(parents=True, exist_ok=True)
    try:
        subprocess.run(
            ["sips", "-Z", str(THUMB_MAX_PX), "-s", "format", "jpeg",
             "-s", "formatOptions", "80", str(src), "--out", str(thumb)],
            check=True, capture_output=True, timeout=30,
        )
        return True
    except (subprocess.CalledProcessError, subprocess.TimeoutExpired, FileNotFoundError):
        return False

